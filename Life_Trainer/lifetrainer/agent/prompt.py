"""에이전트 워크스페이스 프롬프트 — **코드가 만든다.**

## 왜 파일이 아니라 코드인가

프롬프트에 실려야 할 것 중 두 가지가 다른 곳에서 이미 정해져 있다.

    슬래시 명령표      `slash.COMMANDS`
    움직일 수 있는 폴더  `sandbox.Sandbox`

이걸 마크다운에 손으로 베껴 두면 **같은 값을 두 곳에서 각자 관리하게 된다** —
이 저장소의 반복된 실패 2번이고, 하루 경계 하나 바꾸자 3곳이 조용히 어긋난 적이
있다. 그래서 생성한다. 명령을 하나 더하면 프롬프트가 저절로 따라온다.

## 왜 이렇게 짧은가

OpenClaw 기본 워크스페이스는 `AGENTS.md` 7,196바이트를 포함해 11,649바이트고,
그것만으로 시스템 프롬프트가 **7,199 토큰**이었다 (`runtime/agent-gateway.md §3`).
프롬프트 처리 295 tok/s 이므로 그 파일 하나가 **첫 턴에 24초**다.

기본 워크스페이스가 긴 이유는 범용 비서를 상정하기 때문이다 — 기억 파일 관리,
하트비트, 정체성, 소울. 우리 에이전트는 **자기 기록에 답하고 계획을 다루는**
좁은 일을 한다. 그 일에 필요한 문장만 남긴다.

## 무엇을 쓰고 무엇을 안 쓰는가

여기 있는 지시는 전부 **이 저장소가 실제로 겪은 실패**에서 왔다. 지어낸 모범
문구는 한 줄도 없다. 각 줄의 근거는 아래 상수 주석에 달았다.
"""

from __future__ import annotations

from lifetrainer.agent import sandbox as sandbox_mod
from lifetrainer.agent import slash as slash_mod

WORKSPACE_FILE = "AGENTS.md"

# `openclaw agents add` 가 새 워크스페이스에 자동으로 깔아 두는 범용 인격 파일들.
# 게이트웨이는 이것들을 **전부 시스템 프롬프트에 주입한다** — 실측 6,122바이트
# (약 1,700 토큰)가 "너는 누구인가 · 소울 · 하트비트" 로 채워졌다.
#
# ★ 우리 에이전트에게는 해가 된다. `BOOTSTRAP.md` 는 "정체를 찾고 이 파일을 지워라"
#   라고 지시하는 파일이라, 첫 턴에 모델이 사용자 질문 대신 자기소개를 시작한다.
#   `SOUL.md`·`IDENTITY.md` 의 범용 인격은 `AGENTS.md` 의 역할 정의와 경쟁한다.
#
# ★★ **지우면 게이트웨이가 다시 만든다.** 재기동할 때 없는 파일을 시드하기 때문에,
#   삭제는 다음 restart 까지만 유효하다. 이 저장소가 이미 두 번 밟은 부류다 —
#   `nvpower.sh` 가 부팅마다 심링크를 되돌리고, `openclaw daemon install` 이
#   유닛을 다시 생성한다. **비워서 남긴다.** 파일이 있으면 시드가 안 돈다.
#   (`BOOTSTRAP.md` 만은 예외다 — 원래 한 번 쓰고 지우는 파일이라 다시 안 생긴다.)
SEEDED_FILES: tuple[str, ...] = (
    "SOUL.md",
    "IDENTITY.md",
    "USER.md",
    "TOOLS.md",
    "HEARTBEAT.md",
)

# 시드 파일을 지우는 대신 넣어 두는 내용. 빈 파일이 아니라 한 줄인 이유는
# **사람이 나중에 열어봤을 때 왜 비었는지 알아야** 하기 때문이다.
STUB_BODY = "(사용하지 않는다 — AGENTS.md 를 본다)\n"

# 한 번 쓰고 지우는 파일. 이것만은 정말로 지운다 (게이트웨이가 다시 안 만든다).
BOOTSTRAP_FILE = "BOOTSTRAP.md"

# 프롬프트 상한(토큰). 근거: 프롬프트 처리 295 tok/s 이므로 1,000 토큰이면 3.4초다.
# 워크스페이스는 **하루 종일 안 변하는 층**이라 프롬프트 캐시가 계속 물지만,
# 세션이 새로 열릴 때마다 한 번은 전액을 낸다.
PROMPT_TOKEN_BUDGET = 1000


def build_agents_md(sandbox: sandbox_mod.Sandbox) -> str:
    """`AGENTS.md` 본문. 게이트웨이가 세션 시작 때 통째로 읽는다."""
    return _TEMPLATE.format(
        commands=_command_table(),
        scope=sandbox.describe(),
    )


def _command_table() -> str:
    return "\n".join(f"  {name} {desc}" for name, desc in slash_mod.COMMANDS.items())


# ── 본문 ──────────────────────────────────────────────────────────────
#
# 각 규칙의 출처:
#
# "슬래시를 먼저"       `HANDOFF.md §1` — 슬래시는 밀리초, 자연어는 2~9초.
# "했다고 말하지 마라"   `runtime/agent-gateway.md §4-6` — 8B 가 툴을 안 부르고
#                      "I'll create this as a text file" 로 끝냈다. **에러가 안 났다.**
#                      확인을 요구하면 그 탈출구가 막힌다 (같은 절의 대조 실험).
# "숫자를 만들지 마라"   `CLAUDE.md` — 8B 가 달성률을 지어냈다.
# "빈손이면 빈손이라고"  `HISTORY/2026-08-18-search-fallback-noise.md` — 툴이 빈손일 때
#                      모델이 다른 걸로 대체하거나 출처를 안 밝히면 그걸 사실로 취급한다.
# "계획과 실측을 섞지 마라" `HISTORY/2026-08-17-plan-only-injection-hallucination.md` —
#                      계획만 보고 "다 했다"고 답했다.
# "폴더 밖은 없다"      task 4. 감옥은 코드가 막지만, 모델이 시도 자체를 안 하면
#                      거부 메시지가 프롬프트에 쌓이지 않는다.
_TEMPLATE = """# Life Trainer 에이전트

너는 사용자의 활동 기록·계획·수집 문서에 답하는 온디바이스 비서다.
데이터는 이 기기 밖으로 나가지 않는다.

## 일하는 순서

1. **슬래시로 되는 일은 `slash` 툴로 직접 실행한다.** 계획 추가·조회·완료·삭제·
   기록·요약이 전부 여기 있고 밀리초 만에 끝난다.
{commands}
   ★ 이 명령들은 **네가 `slash` 툴에 넣는 것**이다. 사용자에게 "이 명령을
   실행해보세요" 라고 말하지 마라. 시켰으면 네가 실행하고 결과를 보고한다.
2. 슬래시로 안 되는 것만 다른 툴을 쓴다. 파일 경로는 짧은 이름으로 쓴다.

## 지켜야 할 것

- **시켰으면 해라.** "할까요?" 라고 되묻지 말고 실행한 뒤 결과를 보고한다.
  되묻는 것은 **대상이 정말 특정되지 않을 때만**이다(같은 이름이 둘 이상 등).
  바꿨으면 조회로 확인하고, 확인된 것만 적는다. 부르지 않은 툴의 결과는 상상하지 않는다.
- **숫자도 이름도 툴이 준 그대로 인용한다.** 더하거나 나누지 않고, "활동 10시간"을
  "코딩 10시간"으로 바꿔 부르지 않는다. 라벨을 바꾸는 것도 지어내는 것이다.
- **빈손이면 빈손이라고 말한다.** 다른 것으로 대체하지 말고 출처를 밝힌다.
  모른다고 답하는 것이 지어내는 것보다 낫다.
- **계획(`get_plans`)과 실측(`get_activity_summary`)은 다른 것이다.** 하기로 한 것과
  실제로 한 것이다. 한쪽만 보고 다른 쪽을 단정하지 마라.
- **답은 짧게.** 사용자는 채팅으로 읽는다.

## 움직일 수 있는 범위

{scope}

이 밖의 경로는 거부된다. 소스 코드와 설정 비밀은 열 수 없다.
"""
