-- 008: 아침 다이제스트로 **나간 적 있는** 문서에 표식을 단다
--
-- ★ db.py 와 이 파일이 어긋나면 **db.py 가 맞다** (002 머리말과 같은 규칙).
--   실제 실행은 `_apply_008_doc_digested_at` 이 한다 — `ALTER TABLE` 은 두 번 돌면
--   실패하므로 `_column_exists` 로 감싼다.
--
-- 왜 필요한가: 다이제스트가 **8일 연속 같은 문서 5건**을 보냈다. 원인은 둘이고
-- 이 컬럼은 그중 하나만 고친다.
--
--   ① 최신성 보정이 채점 시점에 굳어 옛 문서가 안 늙었다  → `collect/score.py` 가 고친다
--   ② 한 번 보낸 문서를 거를 방법이 없었다                 → **이 컬럼**
--
-- ①만 고쳐도 부족하다. 반감기가 14일이라 오늘 1등이 2주 동안 1등이다 —
-- *"이미 아는 것을 매일 다시 알린다"* 는 저장소 규칙 §1 의 4번 실패 그대로다.
--
-- 파생 테이블을 비우지 않는다. 새 컬럼 하나뿐이라 기존 롤업·슬롯은 그대로 맞다.
--
-- ★ 기존 8,689건은 NULL 로 남긴다 = "아직 안 보냈다". 실제로는 상위 5건이 나간 적
--   있지만, 그 5건은 재채점 뒤 순위가 내려가므로 굳이 소급해 표시하지 않는다.
--   소급하려면 report.blocks_json 을 파싱해야 하는데, **발송 기록을 파싱해 상태를
--   복원하는 코드**는 다음 사람이 믿을 수 없는 종류다.

ALTER TABLE doc ADD COLUMN digested_at REAL;

